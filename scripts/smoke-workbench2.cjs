const {app,BrowserWindow}=require('electron');
const fs=require('fs'),path=require('path'),os=require('os');
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'axiom-workbench2-'));
const project=path.join(temp,'workspace');
fs.mkdirSync(project,{recursive:true});
fs.writeFileSync(path.join(project,'main.js'),'function hello(){ return 42; }\nhello();\n');
const resultFile=path.join(__dirname,'workbench2-smoke-result.log');
fs.writeFileSync(resultFile,'Starting Workbench 2.0 smoke\n');
const log=(...x)=>fs.appendFileSync(resultFile,x.map(v=>typeof v==='string'?v:JSON.stringify(v)).join(' ')+'\n');
app.setPath('userData',path.join(temp,'userData'));
require('../main');
const wait=ms=>new Promise(r=>setTimeout(r,ms));
const until=async(fn,label)=>{for(let i=0;i<400;i++){try{const v=await fn();if(v)return v;}catch{}await wait(100)}throw Error('Timeout: '+label)};
const timer=setTimeout(()=>{log('TIMEOUT');app.exit(1)},60000);
const finish=code=>{clearTimeout(timer);app.once('quit',()=>{try{fs.rmSync(temp,{recursive:true,force:true})}catch{}});app.exit(code);};
app.whenReady().then(async()=>{try{
  const win=await until(()=>BrowserWindow.getAllWindows()[0],'window');
  await until(()=>win.webContents.executeJavaScript("Boolean(window.axiom&&document.querySelector('.monaco-editor'))"),'workbench');
  const result=await win.webContents.executeJavaScript(`(async()=>{
    const root=${JSON.stringify(project)};
    useWorkspace(await window.axiom.openWorkspacePath(root),false);
    await openFile(root+'\\\\main.js');
    toggleEditorSplit('vertical');
    await new Promise(r=>setTimeout(r,120));
    const splitVertical=document.querySelector('.editor-stage').classList.contains('split-vertical')&&secondaryEditor?.getModel()===editor.getModel();
    toggleEditorSplit('horizontal');
    await new Promise(r=>setTimeout(r,80));
    const splitHorizontal=document.querySelector('.editor-stage').classList.contains('split-horizontal')&&secondaryEditor?.getModel()===editor.getModel();
    toggleEditorSplit('horizontal');
    toggleAuxiliary(true,'outline');
    await new Promise(r=>setTimeout(r,1200));
    const auxiliary=document.body.classList.contains('aux-open')&&document.querySelector('#auxiliaryBar').getAttribute('aria-hidden')==='false';
    const auxOutline=Boolean(document.querySelector('#auxContent .outline-row'));
    togglePanel(true);togglePanelMaximized(true);
    const panelMax=document.querySelector('.main').classList.contains('panel-maximized');
    togglePanelMaximized(false);
    notify('Workbench 2.0','Prueba de notificación','success',false);
    toggleNotificationCenter(true);
    const notifications=document.querySelector('#notificationCenter').classList.contains('open')&&document.querySelectorAll('.notification-item').length===1;
    return {splitVertical,splitHorizontal,auxiliary,auxOutline,panelMax,notifications,tabActions:document.querySelectorAll('.tab-actions button').length===3,statusProblems:Boolean(document.querySelector('#statusProblems'))};
  })()`);
  log('RESULT',result);
  const ok=Object.values(result).every(Boolean);
  log(ok?'PASS Workbench 2.0 interactions':'FAIL Workbench 2.0 interactions');
  finish(ok?0:1);
}catch(error){log('ERROR',error.stack||error.message);finish(1);}});
